const { chromium } = require('C:/Users/YOUR_USERNAME/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const path = require('node:path')
const fs = require('node:fs')

async function main() {
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const page = await browser.newPage({ viewport: { width: 1536, height: 1100 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', error => errors.push(String(error)))
  const previewUrl = process.env.S4_PREVIEW_URL || 'http://127.0.0.1:5417/?name=S4-03%20Rootbound%20Cache'
  await page.goto(previewUrl, { waitUntil: 'networkidle', timeout: 120000 })
  await page.waitForFunction(() => document.querySelector('#loading').classList.contains('hidden'), { timeout: 120000 })
  await page.waitForTimeout(2500)
  const stats = await page.locator('#build-stats').innerText()
  await page.mouse.move(768, 550)
  await page.mouse.wheel(0, -100)
  await page.waitForTimeout(1000)
  await page.screenshot({ path: path.join(__dirname, 'preview-default.png') })
  const canvas = await page.locator('#preview').boundingBox()
  await page.mouse.move(canvas.x + canvas.width / 2, canvas.y + canvas.height / 2)
  await page.mouse.down()
  await page.mouse.move(canvas.x + canvas.width / 2 - 262, canvas.y + canvas.height / 2, { steps: 30 })
  await page.mouse.up()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: path.join(__dirname, 'preview-reverse.png') })
  await page.locator('#lighting-toggle').click()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: path.join(__dirname, 'preview-night.png') })
  const response = await page.request.get(new URL('/__minecraft_builder__/build.nbt', previewUrl).href)
  const servedBytes = await response.body()
  const candidateBytes = fs.readFileSync(path.join(__dirname, 'incoming/S4-03/room.nbt'))
  if (!servedBytes.equals(candidateBytes)) errors.push('Viewer NBT differs from final candidate')
  const sha256 = require('node:crypto').createHash('sha256').update(servedBytes).digest('hex')
  fs.writeFileSync(path.join(__dirname, 'preview-check.json'), JSON.stringify({ status: errors.length ? 'FAIL' : 'PASS', renderer: 'Lodestone ThreeStructureRenderer / Edge headless WebGL', previewUrl, sha256, stats, errors }, null, 2))
  await browser.close()
  if (errors.length) throw new Error(errors.join('\n'))
}
main().catch(error => { console.error(error); process.exit(1) })

