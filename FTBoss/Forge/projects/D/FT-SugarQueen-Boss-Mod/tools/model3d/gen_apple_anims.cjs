const f = (n) => String(Math.round(n * 1000) / 1000);
const K = (pairs) => { const o = {}; for (const p of pairs) o[f(p[0])] = p[1]; return o; };
/** 幅度缩放(关节按比例分担动作) */
const sc = (pairs, k) => pairs.map((p) => [p[0], p[1].map((v) => Math.round(v * k * 100) / 100)]);
/** 延迟跟随 */
const lag = (pairs, d, len) => pairs.map((p) => [Math.min(len, p[0] + d), p[1]]);
const add = (pairs, d) => pairs.map((p) => [p[0] + d, p[1]]);
/** 连发后坐 */
function burst(aim, kick, settle, shots, gap) {
    const out = [];
    shots.forEach((s, i) => {
        const d = [1, 0.86, 0.74, 0.62, 0.52][i] || 0.5;
        out.push([s, aim.map((a, k) => a + kick[k] * d)]);
        out.push([s + gap, aim.map((a, k) => a + settle[k] * d)]);
    });
    return out;
}
/** 三节布料链: 幅度 45% / 70% / 100%, 延迟 0 / +step / +2step */
function cloth(bones, names, pairs, len, step, wave = [0.45, 0.72, 1.0]) {
    names.forEach((n, i) => { bones[n] = { rotation: K(lag(sc(pairs, wave[i] || 1), i * step, len)) }; });
}
/** 金腰带: 硬质腰带只轻微跟摆(0.32), 扣子像松扣一样晃得更多更晚(2026-09-12 取代原金链) */
function beltBand(bones, pairs, len) {
    bones.belt = { rotation: K(lag(sc(pairs, 0.32), 0.03, len)) };
    bones.buckle = { rotation: K(lag(pairs, 0.08, len)) };
}
/** 四条腿: 大腿 55% + 小腿 75%(膝盖晚 0.05s); 长度由最后一帧自动推断, 避免越界 */
function legs4(bones, upPairs, loPairs) {
    const end = Math.max(...upPairs.map((p) => p[0]), ...loPairs.map((p) => p[0]));
    for (const nm of ['leg_fl', 'leg_fr', 'leg_bl', 'leg_br']) {
        bones[nm + '_up'] = { rotation: K(sc(upPairs, 0.55)) };
        bones[nm + '_lo'] = { rotation: K(lag(sc(loPairs, 0.75), 0.05, end)) };
    }
}
/** 眉毛(表情): 0=平 1=怒(内低外高) -1=惊(抬起) */
function brows(bones, base, angryPairs, len) {
    bones.brow_l = { rotation: K(angryPairs.map((p) => [p[0], [p[1][0], p[1][1], p[1][2] - base * 6]])) };
    bones.brow_r = { rotation: K(angryPairs.map((p) => [p[0], [p[1][0], p[1][1], p[1][2] + base * 6]])) };
}
/** 让上半果跟着下半果走, 并按 k 反向补位(脊柱) */
function spine(bones, pairs, k) {
    bones.body = { rotation: K(pairs) };
    bones.upper = { rotation: K(sc(pairs, k)) };
}

