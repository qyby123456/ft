const fs = require('fs');
const path = require('path');
const {decodePNG} = require('../../png.cjs');
const core = require('../../boss_materials_refine/shepherd/render.cjs');
const {blank,paste,text,rectangle,save,render} = core;
function previews(root,output) {
  const resource=path.join(root,'src/main/resources/assets/ftboss');
  const model=JSON.parse(fs.readFileSync(path.join(resource,'models/item/boss_relics/shepherd_whistle_charm.json'),'utf8'));
  const texture=decodePNG(path.join(resource,'textures/item/boss_relics/shepherd_whistle_charm.png'));
  const icon=decodePNG(path.join(resource,'textures/item/shepherd_whistle_charm.png'));
  const sheet=blank(1120,1210);
  text(sheet,'BENGER / WHISTLE PENDANT',36,30,4,[236,225,190]);
  text(sheet,'FINAL RUNTIME JSON + TEXTURE / ORTHOGRAPHIC',36,78,2,[143,167,143]);
  const views=[['FRONT / NORTH',[0,0,-1]],['BACK / SOUTH',[0,0,1]],['LEFT / WEST',[-1,0,0]],['RIGHT / EAST',[1,0,0]]];
  views.forEach(([label,camera],index)=>{
    const x=28+(index%2)*550,y=120+Math.floor(index/2)*530;
    rectangle(sheet,x,y,514,505,[37,45,42]);
    const image=render(model,texture,{camera,width:480,height:440,scale:29,center:[8,8.6,8]});
    paste(sheet,image,x+17,y+22);text(sheet,label,x+25,y+470,3,[213,221,194]);
    save(path.join(output,['front.png','back.png','left.png','right.png'][index]),image);
  });
  text(sheet,'CARVED BONE / BRASS / BLACK ENAMEL / GRASS CORD',36,1180,2,[144,164,145]);
  save(path.join(output,'four_views.png'),sheet);
  const detail=blank(1280,1040);
  text(detail,'PASTURE WHISTLE PENDANT',38,30,4,[236,225,190]);
  text(detail,'BENGER / FTBOSS:SHEPHERD_WHISTLE_CHARM',40,79,2,[143,167,143]);
  const hero=render(model,texture,{width:750,height:850,scale:54,camera:[-.75,.36,-1],roll:-12,center:[8,8.6,8]});
  paste(detail,hero,0,130);save(path.join(output,'detail_oblique.png'),hero);
  ['01 / OPEN WINDWAY','02 / RECESSED FIPPLE','03 / BONE RESONATOR','04 / PAW ENAMEL INLAY','05 / SEWN LEATHER LOOP'].forEach((label,index)=>text(detail,label,782,142+index*34,2));
  const rear=render(model,texture,{width:440,height:410,scale:30,camera:[.72,.35,1],center:[8,8.6,8]});
  paste(detail,rear,790,335);save(path.join(output,'detail_rear.png'),rear);
  paste(detail,icon,824,796,4);paste(detail,icon,1040,833,1);
  text(detail,'32 PX AT 4X',796,949,2,[143,167,143]);text(detail,'NATIVE',1015,889,2,[143,167,143]);
  text(detail,'EDITABLE BLOCKBENCH / SEPARATE GUI ICON / FINAL RUNTIME ASSETS',38,1009,2,[143,167,143]);
  save(path.join(output,'detail_and_icon.png'),detail);
  const icons=blank(980,480);
  text(icons,'WHISTLE PENDANT / INVENTORY ICON',30,25,3,[236,225,190]);
  paste(icons,icon,45,103,8);paste(icons,icon,371,228);
  const small=render(model,texture,{width:410,height:342,scale:24,camera:[-.35,.28,-1],roll:-12,center:[8,8.6,8]});
  paste(icons,small,520,78);text(icons,'32 PX AT 8X',52,423,2);text(icons,'1X',375,285,2);text(icons,'RUNTIME MODEL',566,423,2);
  save(path.join(output,'icon_comparison.png'),icons);
  const pair=blank(1200,840);
  text(pair,'BENGER / MATERIAL TO HEIRLOOM',38,30,4,[236,225,190]);
  text(pair,'SHARED BONE + GRASS + BRASS / DIFFERENT CRAFT STAGES',40,80,2,[143,167,143]);
  const material=JSON.parse(fs.readFileSync(path.join(resource,'models/item/boss_materials/shepherd_material.json'),'utf8'));
  const materialTexture=decodePNG(path.join(resource,'textures/item/boss_materials/shepherd.png'));
  const first=render(material,materialTexture,{width:540,height:610,scale:42,camera:[-.65,.32,-1],roll:18,center:[8.1,8.5,8]});
  const second=render(model,texture,{width:540,height:610,scale:42,camera:[-.65,.32,-1],roll:-12,center:[8,8.6,8]});
  paste(pair,first,35,135);paste(pair,second,620,135);
  text(pair,'RAW / WHISTLE BONE',80,752,3,[209,215,187]);text(pair,'FINISHED / PENDANT',680,752,3,[209,215,187]);
  save(path.join(output,'material_relic_pair.png'),pair);
}
module.exports={...core,previews};
if(require.main===module) previews(path.resolve(__dirname,'../../../..'),path.resolve(__dirname,'../../../../art/boss_relics/refine/shepherd'));
