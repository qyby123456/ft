const fs = require('fs');
const path = require('path');
const { root, render, save, canvas, blit, text } = require('../../boss_materials_refine/tea/render.cjs');
const { decodePNG } = require('../../png.cjs');
const art = path.join(root, 'art/boss_relics/refine/tea');
const model = JSON.parse(fs.readFileSync(path.join(root, 'src/main/resources/assets/ftboss/models/item/boss_relics/tea_heart_pendant.json')));
const texture = decodePNG(path.join(root, 'src/main/resources/assets/ftboss/textures/item/boss_relics/tea_heart_pendant.png'));
const icon = decodePNG(path.join(root, 'src/main/resources/assets/ftboss/textures/item/tea_heart_pendant.png'));
const oldIcon = decodePNG(path.join(root, '_work/boss-relics-refine-20261021/tea/backup/src/main/resources/assets/ftboss/textures/item/tea_heart_pendant.png'));
const materialIcon = decodePNG(path.join(root, 'src/main/resources/assets/ftboss/textures/item/tea_material.png'));
const center = [8, 8.2, 8];
const views = [['FRONT', 0], ['BACK', 180], ['LEFT', 270], ['RIGHT', 90]];
const sheet = canvas(1520, 680);
text(sheet, 'SAYA / TEA HEART PENDANT', 34, 27, 5);
text(sheet, 'FINAL RUNTIME JSON + PER-FACE UV / FOUR VIEWS', 34, 72, 3, [136, 164, 145, 255]);
for (let index = 0; index < views.length; index++) {
  const [name, yaw] = views[index];
  const image = render(model, texture, { width: 360, height: 500, yaw, center, scale: 32 });
  save(path.join(art, name.toLowerCase() + '.png'), image);
  blit(sheet, image, 10 + index * 380, 113);
  text(sheet, name, 123 + index * 380, 635, 3);
}
save(path.join(art, 'four_views.png'), sheet);
const angled = render(model, texture, { width: 620, height: 720, yaw: -27, pitch: 13, scale: 45, center });
save(path.join(art, 'angled_detail.png'), angled);
const presentation = canvas(1280, 930);
text(presentation, 'TEA HEART PENDANT', 36, 30, 6);
text(presentation, 'SAYA / FTBOSS:TEA_HEART_PENDANT', 38, 83, 3, [144, 170, 147, 255]);
blit(presentation, angled, 30, 130);
text(presentation, 'FINISHED RELIC', 730, 180, 4);
text(presentation, '32 PX / 8X PIXEL VIEW', 730, 225, 3);
blit(presentation, icon, 805, 280, 8);
blit(presentation, icon, 1164, 496);
text(presentation, 'GILDED LEAF FRAME', 730, 620, 3);
text(presentation, 'INSET MINT TEA HEART', 730, 661, 3);
text(presentation, 'VEINS / BAIL / OPEN RING', 730, 702, 3);
text(presentation, 'CARVED BACK / REAL DEPTH', 730, 743, 3);
text(presentation, 'EDITABLE BLOCKBENCH / NO GAMEPLAY EDITS', 36, 882, 3, [144, 170, 147, 255]);
save(path.join(art, 'presentation.png'), presentation);
const icons = canvas(1050, 470);
text(icons, 'RELIC / RAW MATERIAL / PREVIOUS ICON', 25, 26, 3);
blit(icons, icon, 40, 90, 9);
blit(icons, materialIcon, 390, 90, 9);
blit(icons, oldIcon, 790, 170, 8);
text(icons, 'FINISHED RELIC', 45, 410, 3);
text(icons, 'TEA FIBER', 420, 410, 3);
text(icons, 'OLD', 810, 410, 3);
blit(icons, icon, 975, 90);
save(path.join(art, 'icon_material_comparison.png'), icons);
const enlargedAtlas = canvas(texture.w * 4, texture.h * 4);
blit(enlargedAtlas, texture, 0, 0, 4);
save(path.join(art, 'atlas_4x.png'), enlargedAtlas);
console.log('Rendered tea relic final runtime four views, angled detail, icon and raw-material comparison.');
