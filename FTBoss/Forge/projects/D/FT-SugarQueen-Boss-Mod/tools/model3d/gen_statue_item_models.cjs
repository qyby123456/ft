/* Generate 3D inventory models for the boss statues.
   The placed statue is a DoublePlantBlock: two block models (lower / upper).
   For the inventory we merge both halves into one 16-unit-tall model by
   scaling the whole 32-unit statue by 0.5 about the block centre, so the
   stock minecraft:block/block display transforms work unchanged.

     x' = (x - 8) * 0.5 + 8      z' = (z - 8) * 0.5 + 8
     y' = y * 0.5                (lower half, model space 0..16)
     y' = (y + 16) * 0.5         (upper half, occupies 8..16)

   Usage: node gen_statue_item_models.cjs <assetsRoot> [id...]
*/
const fs = require('fs');
const path = require('path');
const root = process.argv[2];
const only = process.argv.slice(3);
const ALL = ['sugar_queen', 'butcher', 'saya', 'wine_barrel', 'rat_swarm', 'defect', 'compost', 'apple'];
const ids = only.length ? only : ALL;

const rd = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const r2 = (n) => Math.round(n * 1000) / 1000;

function xf(v, isUpper) {
  const [x, y, z] = v;
  return [r2((x - 8) * 0.5 + 8), r2(isUpper ? (y + 16) * 0.5 : y * 0.5), r2((z - 8) * 0.5 + 8)];
}

function convert(el, isUpper) {
  const out = JSON.parse(JSON.stringify(el));
  out.from = xf(el.from, isUpper);
  out.to = xf(el.to, isUpper);
  if (out.rotation && out.rotation.origin) out.rotation.origin = xf(out.rotation.origin, isUpper);
  return out;
}

let made = 0;
for (const id of ids) {
  const lowerPath = path.join(root, 'models/block/statue_' + id + '_lower_painted.json');
  const upperPath = path.join(root, 'models/block/statue_' + id + '_upper_painted.json');
  if (!fs.existsSync(lowerPath) || !fs.existsSync(upperPath)) {
    console.log('  skip ' + id + ' (missing painted halves)');
    continue;
  }
  const lower = rd(lowerPath);
  const upper = rd(upperPath);
  if (lower.loader === 'forge:obj' || upper.loader === 'forge:obj') {
    console.log('  skip ' + id + ' (complete OBJ item is generated by gen_boss_statues.cjs)');
    continue;
  }

  /* both halves share the painted texture map; take the first real entry */
  const tex = {};
  for (const src of [upper, lower]) {
    for (const k in src.textures || {}) {
      if (k === 'particle') continue;
      if (!tex[k]) tex[k] = src.textures[k];
    }
  }
  const first = Object.values(tex)[0] || 'ftboss:block/statue_' + id;
  tex.particle = (lower.textures && lower.textures.particle) || first;

  const elements = [
    ...lower.elements.map((e) => convert(e, false)),
    ...upper.elements.map((e) => convert(e, true)),
  ];

  const model = {
    parent: 'minecraft:block/block',
    ambientocclusion: false,
    textures: tex,
    elements,
  };
  const outPath = path.join(root, 'models/item/statue_' + id + '.json');
  fs.writeFileSync(outPath, JSON.stringify(model, null, 2) + '\n');

  /* sanity: everything must fit the 0..16 block space */
  let bad = 0;
  for (const e of elements) for (const v of [...e.from, ...e.to]) if (v < -0.5 || v > 16.5) bad++;
  console.log('  ' + id.padEnd(13) + ' elements=' + String(elements.length).padStart(3) +
    '  tex=' + first + (bad ? '  !! ' + bad + ' out-of-range' : '  ok'));
  made++;
}
console.log('wrote ' + made + ' statue item model(s)');
