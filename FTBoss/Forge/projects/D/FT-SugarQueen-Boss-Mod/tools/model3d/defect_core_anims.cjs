/* ============================================================================
 * ① 分段披风展开(2026-09-11 参考桌面 YSM 模型的手法: 布料要分段才有波浪)
 * 手写时仍然只写"整块披风"的 cape_back / cape_l / cape_r, 这一步自动展开成 7 根链式骨骼:
 *   背 3 段(cape_back1→2→3) / 左右各 2 段(cape_l1→2, cape_r1→2)
 * 越靠下摆摆幅越大(0.6× → 1.0× → 1.5×)。
 * 循环动画用"相位环绕重采样"(关键帧时刻不变, 只把值错开) => 衔接处不会跳;
 * 一次性动画用"时间延迟"(布料滞后于身体, 甩出去的感觉)。
 * ========================================================================== */
function channelValue(channel, t, len, wrap) {
    const keys = Object.keys(channel).map(k => [parseFloat(k), channel[k]])
        .filter(e => !isNaN(e[0]) && Array.isArray(e[1])).sort((a, b) => a[0] - b[0]);
    if (!keys.length) return [0, 0, 0];
    if (wrap) t = ((t % len) + len) % len;
    if (t <= keys[0][0]) return keys[0][1];
    const last = keys[keys.length - 1];
    if (t >= last[0]) return last[1];
    for (let i = 0; i < keys.length - 1; i++) {
        const [ta, va] = keys[i], [tb, vb] = keys[i + 1];
        if (t >= ta && t <= tb) {
            const k = (t - ta) / Math.max(1e-6, tb - ta);
            return [0, 1, 2].map(j => va[j] + (vb[j] - va[j]) * k);
        }
    }
    return last[1];
}

function expandCape(anims) {
    for (const anim of Object.values(anims)) {
        const bones = anim.bones || {};
        const src = { back: bones.cape_back, l: bones.cape_l, r: bones.cape_r };
        if (!src.back && !src.l && !src.r) continue;
        const len = anim.animation_length || 1;
        const wrap = anim.loop === true;
        const plan = [
            ['cape_back1', src.back, 0.6, 0.00], ['cape_back2', src.back, 1.0, 0.05],
            ['cape_back3', src.back, 1.35, 0.09], ['cape_back4', src.back, 1.7, 0.13]
            // 2026-09-11 v11: 披风 3 段 → **4 段**(上窄下宽, 越靠下摆幅越大 => 更像布料)
            // 注: 左右侧披风片(cape_l*/cape_r*)已按用户要求删除(它们看起来像"第三条手臂")
        ];
        for (const [name, s, mult, delay] of plan) {
            if (!s) continue;
            const ch = {};
            for (const key of ['rotation', 'position']) {
                if (!s[key]) continue;
                const out = {};
                for (const t of Object.keys(s[key])) {
                    const tt = parseFloat(t);
                    const v = wrap ? channelValue(s[key], tt - delay, len, true)
                                   : channelValue(s[key], Math.max(0, tt - delay), len, false);
                    out[(wrap ? tt : Math.min(len, tt + delay)).toFixed(2)] = [v[0] * mult, v[1] * mult, v[2] * mult];
                }
                ch[key] = out;
            }
            bones[name] = ch;
        }
        delete bones.cape_back; delete bones.cape_l; delete bones.cape_r;
    }
    return anims;
}

/* ============================================================================
 * ② 密集烘焙(2026-09-11 参考 YSM: 专业动画就是"每 1/24 秒一个关键帧")
 * 手写只写"姿势"关键帧, 这一步按 smoothstep 把每段插成 **24fps**(循环动画 12fps)的密集帧,
 * 于是 GeckoLib 的线性插值看起来就是连续的缓入缓出曲线 —— 和 YSM 烘焙动画一个道理。
 * ========================================================================== */
function smoothChannel(keys, fps) {
    const list = Object.keys(keys).map(k => [parseFloat(k), keys[k]])
        .filter(e => !isNaN(e[0]) && Array.isArray(e[1]))
        .sort((a, b) => a[0] - b[0]);
    if (list.length < 2) return keys;
    const out = {};
    const put = (t, v) => { out[t.toFixed(3)] = v.map(x => Math.round(x * 100) / 100); };
    for (let i = 0; i < list.length - 1; i++) {
        const [t0, v0] = list[i], [t1, v1] = list[i + 1];
        const sub = Math.max(1, Math.round((t1 - t0) * fps));   // 该段按 fps 细分
        for (let s = 0; s < sub; s++) {
            const k = s / sub;
            const e = k * k * (3 - 2 * k);                     // smoothstep 缓入缓出
            put(t0 + (t1 - t0) * k, [0, 1, 2].map(j => v0[j] + (v1[j] - v0[j]) * e));
        }
    }
    const [tl, vl] = list[list.length - 1];
    put(tl, vl);
    return out;
}

function smoothAll(anims) {
    for (const anim of Object.values(anims)) {
        const fps = anim.loop === true ? 12 : 24;   // 循环慢动作 12fps 就够, 一次性动作 24fps
        for (const bone of Object.values(anim.bones || {})) {
            for (const ch of ['rotation', 'position', 'scale']) {
                if (bone[ch]) bone[ch] = smoothChannel(bone[ch], fps);
            }
        }
    }
    return anims;
}

