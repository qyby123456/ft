/* ======================= chestCast: 施法时双手抬到胸前(2026-09-12 按用户要求) =======================
 * 参照姜饼人的抬手: 大臂前抬 -62° + 内收 24°, 前臂弯 68° -> 双手停在胸口。
 * 按"动作幅度"做包络融合: 抬手越明显越贴近该姿势, 收招时回到原姿势, 不会僵住。
 * 只作用于 cast / cast_* / orb_summon; beam 与 phase_shift 的"高举"保持不动。 */
function chestCast(anims) {
    const r2 = v => Math.round(v * 100) / 100;
    /* 目标: 双手抬到胸前(参考姜饼人: 大臂 -62 / 内收 24 / 前臂 68) */
    const AX = -62, AZ = 24, FX = 68;
    for (const [name, anim] of Object.entries(anims)) {
        if (!/\.(cast|cast_\w+|orb_summon)$/.test(name)) continue;      // beam / phase_shift 不动
        // 2026-09-12 修正: 优先用动画声明的 animation_length, 否则再扫关键帧
        // (原写法会被其它骨骼的 1.0s 帧带偏, 导致 0.85s 的 orb_summon 里写到 1.0s -> 验证器报"关键帧超过动画长度")
        let len = (typeof anim.animation_length === 'number' && anim.animation_length > 0) ? anim.animation_length : 0;
        if (len <= 0) {
            len = 1.0;
            for (const bone of Object.values(anim.bones)) {
                for (const ch of ['rotation', 'position', 'scale']) {
                    if (!ch || !bone[ch]) continue;
                    for (const t of Object.keys(bone[ch])) len = Math.max(len, parseFloat(t));
                }
            }
        }
        /* 关键帧弧线(按比例): 0 放下 -> 0.30 抬到胸前 -> 0.72 保持 -> 0.88 收 -> 1.0 放下 */
        const K = [0.0, 0.30, 0.72, 0.88, 1.0];
        const AXS = [0, AX, AX, -26, 0];
        const AZS = [8, AZ, AZ, 14, 8];
        const FXS = [0, FX, FX, 22, 0];
        for (const side of ['l', 'r']) {
            const sign = side === 'l' ? 1 : -1;
            const arm = {}; const fore = {};
            for (let i = 0; i < K.length; i++) {
                const t = (K[i] * len).toFixed(3);
                arm[t] = [r2(AXS[i]), 0, r2(sign * AZS[i])];
                fore[t] = [r2(FXS[i]), 0, 0];
            }
            anim.bones['arm_' + side] = { rotation: arm };
            anim.bones['forearm_' + side] = { rotation: fore };
        }
    }
    return anims;
}

