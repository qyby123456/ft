/* ============================================================================
 * ④ 镜像生成右转(2026-09-11): 只手写 turn_l, turn_r 由这里自动镜像 ——
 * 骨骼名 _l ↔ _r 互换, 旋转的 y/z 取反, 位移的 x 取反。
 * ========================================================================== */
function mirrorAnim(anim) {
    const swap = n => n.endsWith('_l') ? n.slice(0, -2) + '_r' : (n.endsWith('_r') ? n.slice(0, -2) + '_l' : n);
    const out = { loop: anim.loop, animation_length: anim.animation_length, bones: {} };
    for (const [name, ch] of Object.entries(anim.bones)) {
        const o = {};
        for (const axis of ['rotation', 'position', 'scale']) {
            if (!ch[axis]) continue;
            const kk = {};
            for (const [t, v] of Object.entries(ch[axis])) {
                kk[t] = axis === 'rotation' ? [v[0], -v[1], -v[2]]
                    : axis === 'position' ? [-v[0], v[1], v[2]] : v;
            }
            o[axis] = kk;
        }
        out.bones[swap(name)] = o;
    }
    return out;
}

