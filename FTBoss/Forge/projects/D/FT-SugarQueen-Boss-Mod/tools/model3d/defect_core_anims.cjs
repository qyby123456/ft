/* ============================================================================
 * ⑥ 手部施法动作(2026-09-11 按用户要求"模型确实[缺少]手部施法动画"):
 *    手 = 前臂的 0.55×, 爪 = 在前臂基础上**逐根递进张开**(第 2/3 根各多 8°),
 *    于是每次施法都能看到"手掌翻出去、爪张开"的手势, 而不是只抬胳膊。
 * ========================================================================== */
function handGesture(anims) {
    for (const [name, anim] of Object.entries(anims)) {
        if (!/\.(cast|cast_\w+|orb_summon|beam)$/.test(name)) continue;
        for (const side of ['l', 'r']) {
            const arm = anim.bones['arm_' + side];
            const sign = side === 'l' ? 1 : -1;
            if (arm && arm.rotation) {
                // 手掌: 手臂幅度的 0.85 倍 + 额外的"翻掌"(z 轴 ±18°), 抬得越高翻得越明显
                const h = {};
                for (const [t, v] of Object.entries(arm.rotation)) {
                    const lift = Math.min(1, Math.abs(v[0]) / 40);
                    h[t] = [Math.round(v[0] * 0.85 * 100) / 100,
                            Math.round(v[1] * 0.5 * 100) / 100,
                            Math.round((v[2] * 0.8 + sign * 18 * lift) * 100) / 100];
                }
                anim.bones['hand_' + side] = { rotation: h };
            }
            // 爪子: 摆幅越大张得越开(0~52°), 三根之间再扇形错开 14°
            const src = (anim.bones['fingers_' + side] && anim.bones['fingers_' + side].rotation)
                ? anim.bones['fingers_' + side].rotation : (arm && arm.rotation ? arm.rotation : null);
            if (!src) continue;
            for (let i = 0; i < 3; i++) {
                const g = {};
                for (const [t, v] of Object.entries(src)) {
                    const swing = Math.min(1, Math.abs(v[0]) / 45 + Math.abs(v[2]) / 60);
                    const open = -52 * swing - i * 14;              // 负角 = 张开
                    g[t] = [Math.round((v[0] * 0.4 + open) * 100) / 100, 0,
                            Math.round((v[2] * 0.3 + sign * i * 4) * 100) / 100];
                }
                anim.bones['claw_' + side + (i + 1)] = { rotation: g };
            }
        }
    }
    return anims;
}

