/** 左右镜像: 左臂用 [x, y, z], 右臂用 [x, -y, -z] */
function mirror(times, triples) {
    const L = {}, R = {};
    for (let i = 0; i < times.length; i++) {
        const t = triples[i];
        L[times[i]] = [t[0], t[1], t[2]];
        R[times[i]] = [t[0], -t[1], -t[2]];
    }
    return { L, R };
}

/** 把一次 idle 里的"逐爪相位差"展开: 每根爪子延迟 idx*0.06 秒 */
function claws(spread, curl, length) {
    const out = {};
    for (let i = 1; i <= 3; i++) {
        const d = (i - 1) * 0.08;
        out['0.0'] = [0, 0, spread * (i - 1)];
        out[(0.6 + d).toFixed(2)] = [curl, 0, spread * (i - 1) + curl * 0.4];
        out[(1.4 + d).toFixed(2)] = [0, 0, spread * (i - 1)];
        if (length > 2.0) out[length.toFixed(2)] = [0, 0, spread * (i - 1)];
    }
    return out;
}

/** 一套"呼吸/悬浮"基础通道(所有循环动画共用, 保证 idle 与 float_move 衔接不跳) */
